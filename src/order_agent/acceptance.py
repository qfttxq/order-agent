"""验收单草稿。

这个模块看起来最不起眼，实际是整份产出里最值钱的部分。

私下收款没有平台兜底，唯一的保护就是「什么叫做完」写没写清楚。
写得模糊，客户可以说「我觉得还不行」；写得可判定，双方都有台阶。

所以每一条验收项都必须满足：给一个第三方看，他能独立判断通过与否。
「效果好」「响应快」「准确率高」这类词一律不许出现。
"""

from __future__ import annotations

from .models import Acceptance, Kind, Signals


def build(kind: Kind, signals: Signals) -> Acceptance:
    if kind is Kind.A:
        return _agent(signals)
    if kind is Kind.D:
        return _data(signals)
    return _kb(signals)


def _kb(signals: Signals) -> Acceptance:
    docs = signals.doc_count or 50
    items = [
        (
            f"语料入库完整性",
            f"约定的 {docs} 份文档全部完成解析入库；随机抽 30 份，逐一检索均能命中对应片段",
        ),
        (
            "检索召回率",
            "在双方确认的评测集上，Recall@5 ≥ 0.85；若诊断阶段实测基线已高于 0.85，"
            "则要求不低于基线值",
        ),
        (
            "答案忠实性",
            "随机抽检 30 条回答，全部能对应到原文片段，无编造内容；"
            "任一条出现编造即视为该项不通过",
        ),
        (
            "语料外拒答",
            "准备 10 个语料中确无答案的问题，其中 ≥ 9 个明确表示「文档中没有」而不是强行作答",
        ),
        (
            "响应延迟",
            "单次提问从发起到返回完整答案，P95 ≤ 5 秒（不含首次冷启动）",
        ),
    ]

    if signals.has("permission"):
        items.append(
            (
                "权限隔离",
                "用两个不同角色的账号登录，A 角色检索不到仅属于 B 角色的文档，抽样 10 份逐一验证",
            )
        )

    if signals.has("integration"):
        items.append(
            (
                "系统对接",
                "在目标系统内可完成提问并收到答案，返回格式与约定一致，连续 20 次无报错",
            )
        )

    return Acceptance(
        items=items,
        excluded=[
            "客户侧服务器、模型 API、存储等费用由客户承担",
            "语料内容的准确性、合法性与版权由客户负责",
            "上线后新增文档类型的解析适配，属新增范围",
            "约定的问题类型之外的问答效果，不作为验收依据",
        ],
        handover=[
            "可运行的系统与完整配置",
            "部署与运维文档（含常见故障处理）",
            "评测集原始数据与交付报告",
            "一次 60 分钟的线上培训与录屏",
        ],
    )


def _agent(signals: Signals) -> Acceptance:
    systems = "、".join(signals.systems[:5]) or "约定的目标系统"
    items = [
        (
            "主流程跑通",
            f"双方确认的每条流程，在真实或等同真实的环境中端到端跑通一次，"
            f"从触发到结束状态正确（涉及系统：{systems}）",
        ),
        (
            "运行成功率",
            "连续执行 100 次，成功完成 ≥ 95 次。"
            "「失败」不含上游系统不可用、账号权限失效、源数据本身缺失这三种情况",
        ),
        (
            "异常正确停止",
            "准备 10 个异常场景（数据缺失、接口超时、权限不足、状态冲突等），"
            "其中 ≥ 9 个能被正确识别并停止，且发出通知，不产生错误写入",
        ),
        (
            "执行可追溯",
            "每次执行可查到：触发时间、每步决策依据、调用结果、最终状态；"
            "任取 10 次执行记录，信息完整",
        ),
        (
            "人工接管",
            "出现异常时可人工介入并继续处理；接管后流程状态正确，不发生重复写入",
        ),
    ]

    return Acceptance(
        items=items,
        excluded=[
            "上游系统的改造、接口开发由客户方协调，不在本次范围",
            "上游系统自身故障导致的失败不计入成功率",
            "约定的流程条数之外的新增流程，属新增范围",
            "客户内部操作规范变化导致的效果下降，需另行评估",
            "不含 7×24 值守与故障即时响应",
        ],
        handover=[
            "可运行的 Agent 与完整配置",
            "部署文档与运行手册",
            "异常处理与人工接管操作说明",
            "测试样本集与成功率测试报告",
            "一次 60 分钟的线上培训与录屏",
        ],
    )


def _data(signals: Signals) -> Acceptance:
    records = signals.doc_count or 1000
    return Acceptance(
        items=[
            ("数据完整性", f"约定的 {records} 条记录全部处理完成，条数核对一致，无静默丢弃"),
            (
                "字段准确率",
                "随机抽取 100 条，人工核对结构化字段，准确率 ≥ 98%",
            ),
            (
                "可重复运行",
                "提供脚本与说明，在干净环境中按文档执行一次，能产出相同结构的结果",
            ),
        ],
        excluded=[
            "源数据本身错误或缺失的内容，不做补录",
            "数据源的合法性与授权由客户负责",
            "超出约定数据源范围的新增采集，属新增范围",
        ],
        handover=[
            "处理脚本与依赖说明",
            "运行说明文档",
            "抽样校验报告",
            "一次 30 分钟的使用说明",
        ],
    )
